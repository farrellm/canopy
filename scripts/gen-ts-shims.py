#!/usr/bin/env python3
"""Generate pointer-taking C shims for tree-sitter's by-value API (DESIGN.md §5A.2).

GHC's FFI cannot pass or return a struct by value. For every `ts_*` prototype in
the vendored `api.h` that takes or returns one of BY_VALUE, this writes a
`tsffi_*` shim that takes a `const T *` in place of each by-value argument and
returns a by-value result through a trailing `T *out`:

    TSNode ts_node_child(TSNode self, uint32_t child_index);
    void tsffi_node_child(const TSNode *self, uint32_t child_index, TSNode *out);

Run from the repository root. With --check, nothing is written, and the exit
status is 1 if the committed shims are not what the vendored header generates.
"""

import argparse
import difflib
import re
import sys
from pathlib import Path

PKG = Path("tree-sitter-ffi")
API_H = PKG / "vendor/tree-sitter/lib/include/tree_sitter/api.h"
OUT_C = PKG / "cbits/tsffi_shims.c"
OUT_H = PKG / "include/tsffi_shims.h"

BY_VALUE = {
    "TSNode",
    "TSPoint",
    "TSRange",
    "TSTreeCursor",
    "TSInput",
    "TSParseOptions",
    "TSLogger",
}

PROTO = re.compile(r"^([A-Za-z_][\w\s\*]*?)\b(ts_\w+)\s*\(([^;{)]*)\)\s*;", re.M)
PARAM = re.compile(r"^(?P<type>.*?[\s\*])(?P<name>\w+)$")


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def norm(s):
    """Collapse whitespace, and write pointers as `T *`/`T **`."""
    s = re.sub(r"\s*\*", " *", " ".join(s.split()))
    return re.sub(r"\* \*", "**", s).strip()


def bare(ty):
    """The struct name of a by-value type, or None. `const TSNode` counts."""
    t = norm(ty)
    if "*" in t:
        return None
    t = re.sub(r"^const\s+", "", t)
    return t if t in BY_VALUE else None


def parse(src):
    protos = []
    for m in PROTO.finditer(strip_comments(src)):
        ret, name, args = norm(m.group(1)), m.group(2), norm(m.group(3))
        params = []
        if args and args != "void":
            for i, p in enumerate(args.split(",")):
                p = norm(p)
                pm = PARAM.match(p)
                # An unnamed parameter (`TSWasmStore *`) ends in `*` or is a
                # bare type; name it by position.
                if p.endswith("*") or not pm or pm.group("type").strip() in ("", "const"):
                    params.append((p, f"arg{i}"))
                else:
                    params.append((norm(pm.group("type")), pm.group("name")))
        protos.append((ret, name, params))
    return protos


def shim(ret, name, params):
    sname = "tsffi_" + name[len("ts_") :]
    decl, call = [], []
    for ty, pname in params:
        s = bare(ty)
        if s:
            decl.append(f"const {s} *{pname}")
            call.append(f"*{pname}")
        else:
            sep = "" if ty.endswith("*") else " "
            decl.append(f"{ty}{sep}{pname}")
            call.append(pname)
    rs = bare(ret)
    if rs:
        decl.append(f"{rs} *out")
        sret = "void"
        body = f"*out = {name}({', '.join(call)});"
    elif ret == "void":
        sret = "void"
        body = f"{name}({', '.join(call)});"
    else:
        sret = ret
        body = f"return {name}({', '.join(call)});"
    sep = "" if sret.endswith("*") else " "
    sig = f"{sret}{sep}{sname}({', '.join(decl) or 'void'})"
    return sig, body


BANNER = """\
/* Generated by scripts/gen-ts-shims.py from {api} ({version}).
 * Do not edit: regenerate (DESIGN.md §5A.2). {count} shims. */
"""


def generate():
    protos = parse(API_H.read_text())
    if not protos:
        sys.exit(f"gen-ts-shims: no prototypes found in {API_H}")
    version = (PKG / "TREE_SITTER_VERSION").read_text().strip()
    shims = [
        shim(r, n, ps)
        for r, n, ps in protos
        if bare(r) or any(bare(t) for t, _ in ps)
    ]
    banner = BANNER.format(api=API_H.relative_to(PKG), version=version, count=len(shims))
    h = [banner, "#ifndef TSFFI_SHIMS_H", "#define TSFFI_SHIMS_H", "",
         "#include <tree_sitter/api.h>", ""]
    h += [f"{sig};" for sig, _ in shims]
    h += ["", "#endif /* TSFFI_SHIMS_H */", ""]
    c = [banner, '#include "tsffi_shims.h"', ""]
    for sig, body in shims:
        c += [f"{sig} {{", f"  {body}", "}", ""]
    return {OUT_H: "\n".join(h), OUT_C: "\n".join(c)}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed shims are stale")
    args = ap.parse_args()
    files = generate()
    if args.check:
        stale = False
        for path, want in files.items():
            have = path.read_text() if path.exists() else ""
            if have != want:
                stale = True
                sys.stdout.writelines(
                    difflib.unified_diff(
                        have.splitlines(True), want.splitlines(True), str(path), "generated"
                    )
                )
        if stale:
            sys.exit("gen-ts-shims: committed shims are stale; run scripts/gen-ts-shims.py")
        print("gen-ts-shims: shims are current")
        return
    for path, text in files.items():
        path.write_text(text)
        print(f"gen-ts-shims: wrote {path}")


if __name__ == "__main__":
    main()
