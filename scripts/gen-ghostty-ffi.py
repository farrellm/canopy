#!/usr/bin/env python3
"""Generates ghostty-vt-ffi's mechanical code from the pinned libghostty-vt
headers (DESIGN.md §3.3), into the committed sources. `--check` regenerates
in memory and fails if a committed file differs, so a pin bump that changes a
header cannot leave the binding behind, and an edit to generated code cannot
survive.

Each template `ghostty-vt-ffi/gen/<path>.in` renders to `ghostty-vt-ffi/<path>`.
A template is the module as written by hand, with directive lines that expand
in place. Each directive is alone on its line, as `{{kind args}}`:

    {{enum H T}}           enum T from header H: newtype, a pattern per value,
                           the Unknown view, COMPLETE, and the tEnum descriptor
    {{enumT H T}}          the same, with each value's input or output type
                           (for keyed get/set enums)
    {{struct H T}}         a plain struct: record, Storable, tLayout descriptor
    {{layout T f1 f2 ..}}  only the descriptor, for a struct written by hand
    {{fn wrapper H T}}     a callback typedef: FunPtr synonym and mkT wrapper
                           (no wrapper when it returns a struct by value)
    {{fn dynamic H T}}     a library function pointer: synonym and callT import
    {{modes}}              modes.h's named modes, as patterns
    {{defines H T P}}      each `#define P…` constant in header H (not a
                           function-like macro), as a pattern of type T: the
                           bit flags and named values a header spells as
                           macros over a scalar typedef
    {{enumrows}}           the layout test's list of EnumRows, one per enum
                           rendered before it
    {{shim F}}             in the C shim header: a static inline pointer shim
                           for function F, which takes or returns a struct by
                           value (DESIGN.md §3.3)
    {{pin}}                ghosttyPinnedCommit, GHOSTTY_COMMIT as a constant,
                           which ghostty-effectful's version check compares
                           with the linked library's (DESIGN.md §4.7)

    {{xenum H T}}, {{xstruct H T}}, {{xfn wrapper|dynamic H T}}, {{xmodes}},
    {{xdefines H T P}}
                           the export-list lines for the matching directive

Names: a pattern is its C name in CamelCase. When that is already a type's
name (GHOSTTY_TERMINAL_RESIZE_WINDOW_GRID vs GhosttyTerminalResizeWindowGrid),
it gets a Tag suffix and a note saying why; when it is its enum's Unknown view
(GHOSTTY_MOUSE_BUTTON_UNKNOWN), a Value suffix. A field is the C field in
camelCase, `data` becoming `data_`.

Run from the repository root. The headers are read from
`_deps/ghostty/<GHOSTTY_COMMIT>/include` (scripts/build-libghostty.sh), or
from `--include`.
"""

import argparse
import re
import sys
from pathlib import Path

PKG = Path("ghostty-vt-ffi")
GEN = PKG / "gen"
BANNER = "Generated by scripts/gen-ghostty-ffi.py from {src}. Edit that, not this."


# * Reading the headers


class Headers:
    def __init__(self, include: Path):
        self.root = include / "ghostty" / "vt"
        if not self.root.is_dir():
            sys.exit(f"gen-ghostty-ffi: no headers at {self.root}; run scripts/build-libghostty.sh")
        self.text = {
            str(p.relative_to(self.root)): p.read_text() for p in sorted(self.root.rglob("*.h"))
        }
        # Every type name the headers declare, for the pattern-name collision rule.
        self.types = set()
        for t in self.text.values():
            self.types |= set(re.findall(r"\}\s*(Ghostty\w+)\s*;", t))
            self.types |= set(re.findall(r"^struct (Ghostty\w+)\s*\{", t, re.M))
        # The struct types, which a function cannot pass by value through GHC's FFI.
        self.structs = set()
        for t in self.text.values():
            s = strip_comments(t)
            for m in re.finditer(r"typedef struct\s*\{", s):
                end = matching_brace(s, m.end() - 1)
                n = re.match(r"\s*(Ghostty\w+)\s*;", s[end + 1 :])
                if n:
                    self.structs.add(n.group(1))
            self.structs |= set(re.findall(r"^struct (Ghostty\w+)\s*\{", s, re.M))

    def get(self, header: str) -> str:
        if header not in self.text:
            sys.exit(f"gen-ghostty-ffi: no header {header}")
        return self.text[header]


def strip_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", text, flags=re.S))


def matching_brace(s: str, i: int) -> int:
    """The index of the brace that closes the one at i."""
    depth = 0
    for j in range(i, len(s)):
        depth += {"{": 1, "}": -1}.get(s[j], 0)
        if depth == 0:
            return j
    sys.exit("gen-ghostty-ffi: unbalanced braces")


def c_decl(ctype: str, name: str) -> str:
    """A C parameter declaration, its stars against the name: `uint8_t **out`."""
    stars = ctype.count("*")
    return f"{ctype.replace('*', '').strip()} {'*' * stars}{name}"


def doc_before(text: str, pos: int):
    """The doc comment that ends right before pos, as paragraphs."""
    m = re.search(r"(/\*\*(?:(?!\*/).)*\*/)\s*$", text[:pos], re.S)
    return clean_doc(m.group(1)) if m else []


def clean_doc(raw: str):
    raw = re.sub(r"^/\*\*<?", "", raw.strip())
    raw = re.sub(r"\*/$", "", raw)
    lines = [re.sub(r"^\s*\* ?", "", l).rstrip() for l in raw.splitlines()]
    text = "\n".join(lines).strip()
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]


def first_para(paras) -> str:
    return " ".join(paras[0].split()) if paras else ""


def sentence(p: str) -> str:
    p = p.strip()
    if p and not p.endswith((".", ":", ")")):
        p += "."
    return p


def type_line(paras):
    for p in paras:
        m = re.match(r"(Input/output|Input|Output) type: (.*)", p)
        if m:
            return f"{m.group(1)} type: @{m.group(2).strip()}@."
    return None


def escape(s: str) -> str:
    """C doc text as Haddock: `code` and Doxygen's @p/@c/@a/@ref word become
    @code@, and markup characters are escaped."""
    s = re.sub(r"@(?:p|c|a|ref)\s+(\w+)", r"`\1`", s)
    s = re.sub(r"`([^`]*)`", lambda m: "@" + m.group(1) + "@", s)
    out, in_code = [], False
    for ch in s:
        if ch == "@":
            in_code = not in_code
            out.append(ch)
        elif ch in "/'\"<>#\\" or (ch in "$*_" and not in_code):
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def camel(c_name: str) -> str:
    return "".join(p[:1] + p[1:].lower() for p in c_name.split("_") if p)


def lower_first(s: str) -> str:
    return s[:1].lower() + s[1:]


def field_name(c: str) -> str:
    parts = c.split("_")
    n = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return {"data": "data_"}.get(n, n)


CTYPE = {
    "size_t": "CSize",
    "bool": "CBool",
    "uint8_t": "Word8",
    "uint16_t": "Word16",
    "uint32_t": "Word32",
    "uint64_t": "Word64",
    "int8_t": "Int8",
    "int32_t": "Int32",
    "intptr_t": "CIntPtr",
    "int": "CInt",
    "char": "CChar",
    "double": "CDouble",
    "float": "CFloat",
}


def htype(ctype: str) -> str:
    ctype = ctype.replace("const ", "").strip()
    if ctype.endswith("*"):
        base = ctype[:-1].strip()
        return "Ptr ()" if base == "void" else f"Ptr {paren(htype(base))}"
    if ctype == "void":
        return "()"
    return CTYPE.get(ctype, ctype)


def paren(t: str) -> str:
    return f"({t})" if " " in t else t


# * Enums


class Gen:
    def __init__(self, headers: Headers, commit: str):
        self.h = headers
        self.commit = commit
        self.rows = []

    def parse_enum(self, header, name):
        text = self.h.get(header)
        m = re.search(
            r"typedef enum GHOSTTY_ENUM_TYPED \{((?:(?!typedef).)*?)\}\s*" + name + ";", text, re.S
        )
        if not m:
            sys.exit(f"gen-ghostty-ffi: no enum {name} in {header}")
        values = []
        for vm in re.finditer(
            r"((?:/\*\*(?:(?!\*/).)*\*/\s*)?)(GHOSTTY_\w+)\s*(?:=[^,]*)?,", m.group(1), re.S
        ):
            if not vm.group(2).endswith("MAX_VALUE"):
                values.append((vm.group(2), clean_doc(vm.group(1)) if vm.group(1) else []))
        return doc_before(text, m.start()), values

    def pattern_name(self, cname, enum=None):
        p = camel(cname)
        if p in self.h.types:
            return p + "Tag", "the struct"
        if enum and p == enum + "Unknown":
            return p + "Value", "the view of values this binding does not name"
        return p, None

    def enum(self, header, name, with_types=False):
        tdoc, values = self.parse_enum(header, name)
        lname, unk = lower_first(name), name + "Unknown"
        out = [
            f"-- | @{name}@: {escape(sentence(first_para(tdoc)))}",
            f"newtype {name} = {name} CInt",
            "  deriving stock (Eq, Show)",
            "  deriving newtype (Storable)",
            "",
        ]
        pats = []
        for cname, doc in values:
            p, renamed = self.pattern_name(cname, name)
            pats.append(p)
            d = escape(sentence(first_para(doc)))
            out.append(f"-- | @{cname}@" + (f": {d}" if d else "."))
            tl = type_line(doc) if with_types else None
            if tl:
                out += ["--", f"-- {escape(tl)}"]
            if renamed:
                suffix = p[len(camel(cname)) :]
                out += ["--", f"-- Named with a @{suffix}@ suffix: the plain name is {renamed}", f"-- '{camel(cname)}'."]
            out += [f"pattern {p} :: {name}", f"pattern {p} = {name} (#const {cname})", ""]
        out += [
            "-- | Any value this binding does not name: a newer library's.",
            f"pattern {unk} :: CInt -> {name}",
            f"pattern {unk} n <- {name} (unnamed {lname}Enum -> Just n)",
            "  where",
            f"    {unk} n = {name} n",
            "",
            "{-# COMPLETE",
            *[f"  {p}," for p in pats],
            f"  {unk}",
            "  #-}",
            "",
            f"-- | Every value of @{name}@, for the layout test (§3.4). It is also what",
            f"-- '{unk}' excludes.",
            f"{lname}Enum :: CEnum",
            f"{lname}Enum =",
            "  CEnum",
            f'    {{ name = "{name}",',
            f"      size = (#size {name}),",
            "      values =",
        ]
        for i, (cname, _) in enumerate(values):
            lead = "        [ " if i == 0 else "          "
            out.append(f'{lead}("{cname}", (#const {cname})){"," if i < len(values) - 1 else ""}')
        out += ["        ]", "    }", ""]
        exports = [f"{name} (..)", *[f"pattern {p}" for p in pats], f"pattern {unk}", f"{lname}Enum"]
        row = [f"    EnumRow {lname}Enum $ \\n -> case {name} (fromInteger n) of"]
        row += [f"      {p} -> True" for p in pats] + [f"      {unk} _ -> False"]
        return out, exports, "\n".join(row)

    # * Structs

    def parse_struct(self, header, name):
        text = self.h.get(header)
        m = re.search(r"typedef struct \{((?:(?!typedef).)*?)\}\s*" + name + ";", text, re.S)
        if not m:
            m = re.search(r"struct " + name + r" \{(.*?)\};", text, re.S)
        if not m:
            sys.exit(f"gen-ghostty-ffi: no struct {name} in {header}")
        fields, pending = [], None
        for tok in re.finditer(r"(/\*\*<?(?:(?!\*/).)*\*/)|([^;/]+);", m.group(1), re.S):
            if tok.group(1):
                if tok.group(1).startswith("/**<") and fields:
                    fields[-1] = (*fields[-1][:2], clean_doc(tok.group(1)))
                else:
                    pending = clean_doc(tok.group(1))
            else:
                decl = " ".join(tok.group(2).split())
                fm = re.match(r"(.*?)(\w+)(\[\d+\])?$", decl)
                if fm.group(3):
                    sys.exit(f"gen-ghostty-ffi: {name}.{fm.group(2)} is an array; write it by hand")
                fields.append((fm.group(1).strip(), fm.group(2), pending or []))
                pending = None
        return doc_before(text, m.start()), fields

    def struct(self, header, name):
        tdoc, fields = self.parse_struct(header, name)
        out = [f"-- | @{name}@: {escape(sentence(first_para(tdoc)))}", f"data {name} = {name}"]
        for i, (ct, fn, fdoc) in enumerate(fields):
            d = escape(sentence(first_para(fdoc)))
            out.append(("  { " if i == 0 else "    ") + f"-- | @{fn}@" + (f": {d}" if d else "."))
            out.append(f"    {field_name(fn)} :: {htype(ct)}{',' if i < len(fields) - 1 else ''}")
        out += [
            "  }",
            "  deriving stock (Eq, Show)",
            "",
            f"instance Storable {name} where",
            f"  sizeOf _ = (#size {name})",
            f"  alignment _ = (#alignment {name})",
            "  peek p =",
            f"    {name}",
        ]
        for i, (_, fn, _) in enumerate(fields):
            out.append(f"      {'<$>' if i == 0 else '<*>'} (#peek {name}, {fn}) p")
        out.append("  poke p s = do")
        out += [f"    (#poke {name}, {fn}) p s.{field_name(fn)}" for _, fn, _ in fields]
        out.append("")
        out += self.layout(name, [fn for _, fn, _ in fields])
        return out, [f"{name} (..)", f"{lower_first(name)}Layout"]

    def layout(self, name, cfields):
        out = [
            f"-- | The layout of @{name}@ as compiled, for the layout test (§3.4).",
            f"{lower_first(name)}Layout :: CStruct",
            f"{lower_first(name)}Layout =",
            "  CStruct",
            f'    {{ name = "{name}",',
            f"      size = (#size {name}),",
            f"      align = (#alignment {name}),",
            "      fields =",
        ]
        for i, fn in enumerate(cfields):
            lead = "        [ " if i == 0 else "          "
            out.append(
                f'{lead}CField "{fn}" (#offset {name}, {fn}) '
                f'(#const GVTFFI_FIELD_SIZE({name}, {fn})){"," if i < len(cfields) - 1 else ""}'
            )
        return out + ["        ]", "    }", ""]

    # * Function pointers

    def parse_fn(self, header, name):
        text = self.h.get(header)
        m = re.search(r"typedef\s+([\w\s\*]+?)\s*\(\s*\*\s*" + name + r"\s*\)\s*\(([^)]*)\)\s*;", text, re.S)
        if not m:
            sys.exit(f"gen-ghostty-ffi: no function pointer type {name} in {header}")
        params = []
        for p in m.group(2).split(","):
            p = " ".join(p.split())
            pm = re.match(r"(.*?)\b(\w+)$", p)
            params.append(pm.group(1).replace("const ", "").strip())
        return doc_before(text, m.start()), m.group(1).strip(), params

    def option_for(self, fn_name):
        """The terminal option whose input type is this callback, if any."""
        _, values = self.parse_enum("terminal.h", "GhosttyTerminalOption")
        for cname, doc in values:
            if any(re.fullmatch(r"Input type: " + fn_name, p) for p in doc):
                return cname
        return None

    def fn(self, mode, header, name):
        doc, ret, cparams = self.parse_fn(header, name)
        by_value = ret not in CTYPE and ret != "void" and not ret.endswith("*")
        by_value_params = [t for t in cparams if t in self.h.structs]
        params = [htype(t) for t in cparams]
        hs = " -> ".join(params + [f"IO {paren(htype(ret))}"])
        paras = [p for p in doc if not p.startswith(("@", "#", "|"))][:2]
        text = " ".join(escape(sentence(" ".join(p.split()))) for p in paras)
        out = [f"-- | @{name}@: {text}"]
        opt = self.option_for(name) if mode == "wrapper" else None
        if opt:
            out += ["--", f"-- Set with @{opt}@."]
        if by_value:
            out += [
                "--",
                f"-- It returns a @{ret}@ by value, which a @wrapper@ cannot make, so a",
                "-- function of this type has to be written in C (§3.3).",
            ]
        if by_value_params:
            what = " and a ".join(f"@{t}@" for t in dict.fromkeys(by_value_params))
            out += [
                "--",
                f"-- It receives a {what} by value, which a @wrapper@ cannot",
                "-- take, so a function of this type has to be written in C (§3.3).",
            ]
        out += [f"type {name} = FunPtr ({hs})", ""]
        exports = [name]
        if mode == "wrapper" and not by_value and not by_value_params:
            out += [
                f"-- | Make a '{name}' from a Haskell function. Free it with",
                "-- 'Foreign.Ptr.freeHaskellFunPtr' once nothing can call it. A call that",
                "-- runs it must be @safe@ (§3.3).",
                'foreign import ccall "wrapper"',
                f"  mk{name} :: ({hs}) -> IO {name}",
                "",
            ]
            exports.append(f"mk{name}")
        elif mode == "dynamic":
            out += [
                f"-- | Call a '{name}'. @unsafe@: it is the library's own function, which",
                "-- does not call back into Haskell.",
                'foreign import ccall unsafe "dynamic"',
                f"  call{name} :: {name} -> {hs}",
                "",
            ]
            exports.append(f"call{name}")
        return out, exports

    # * Modes

    def modes(self):
        text = self.h.get("modes.h")
        ms = re.findall(
            r"#define (GHOSTTY_MODE_\w+)\s+\(ghostty_mode_new\((\d+), (true|false)\)\)\s*/\*\*<\s*(.*?)\s*\*/",
            text,
        )
        out, exports = [], []
        for cname, value, ansi, doc in ms:
            p = camel(cname)
            kind = "ANSI" if ansi == "true" else "DEC private"
            out += [
                f"-- | @{cname}@: {escape(doc)} ({kind} mode {value}).",
                f"pattern {p} :: GhosttyMode",
                f"pattern {p} = (#const {cname})",
                "",
            ]
            exports.append(f"pattern {p}")
        return out, exports

    # * Defines

    def defines(self, header, typ, prefix):
        text = self.h.get(header)
        ds = re.findall(
            r"(?:/\*\*((?:(?!\*/).)*)\*/\s*)?#define (" + prefix + r"\w+)[ \t]+(\S[^\n]*)", text, re.S
        )
        if not ds:
            sys.exit(f"gen-ghostty-ffi: no #define {prefix}… in {header}")
        out, exports = [], []
        for doc, cname, _ in ds:
            p, renamed = self.pattern_name(cname)
            if renamed:
                sys.exit(f"gen-ghostty-ffi: {cname} names a type; a #define cannot take a Tag")
            d = re.sub(r"\s*@ingroup \w+", "", " ".join(" ".join(clean_doc("/**" + doc + "*/")).split()))
            d = escape(sentence(d)) if d else ""
            out += [
                f"-- | @{cname}@" + (f": {d}" if d else "."),
                f"pattern {p} :: {typ}",
                f"pattern {p} = (#const {cname})",
                "",
            ]
            exports.append(f"pattern {p}")
        return out, exports

    # * Shims

    def parse_function(self, name):
        for header, text in self.h.text.items():
            m = re.search(
                r"GHOSTTY_API\s+([^;(]*?)\s*\b" + name + r"\s*\(([^)]*)\)\s*;", strip_comments(text)
            )
            if m:
                params = []
                for p in m.group(2).split(","):
                    p = " ".join(p.split())
                    pm = re.match(r"(.*?)\s*\b(\w+)$", p)
                    params.append((pm.group(1).strip(), pm.group(2)))
                return header, " ".join(m.group(1).split()), params
        sys.exit(f"gen-ghostty-ffi: no function {name}")

    def shim(self, name):
        header, ret, params = self.parse_function(name)
        by_value = [n for t, n in params if t in self.h.structs]
        ret_by_value = ret in self.h.structs
        if not by_value and not ret_by_value:
            sys.exit(f"gen-ghostty-ffi: {name} passes no struct by value; it needs no shim")
        decls = [f"const {t} *{n}" if n in by_value else c_decl(t, n) for t, n in params]
        args = [f"*{n}" if n in by_value else n for _, n in params]
        call = f"{name}({', '.join(args)})"
        what = ", ".join(f"`{n}`" for n in by_value)
        if ret_by_value:
            decls.append(f"{ret} *out_result")
            body, cret = f"*out_result = {call};", "void"
            note = f"/* {name} ({header}), returning its {ret} through a pointer"
            note += f", and taking {what} by pointer. */" if by_value else ". */"
        else:
            body, cret = ("" if ret == "void" else "return ") + call + ";", ret
            note = f"/* {name} ({header}), taking {what} by pointer. */"
        shim_name = "gvtffi_" + name.removeprefix("ghostty_")
        lines = [note, f"static inline {cret} {shim_name}("]
        lines += [f"    {d}{',' if i < len(decls) - 1 else ') {'}" for i, d in enumerate(decls)]
        return lines + [f"  {body}", "}", ""]

    # * Templates

    def expand(self, args):
        kind, rest = args[0], args[1:]
        if kind in ("enum", "enumT"):
            code, _, row = self.enum(*rest, with_types=kind == "enumT")
            self.rows.append(row)
            return code
        if kind == "xenum":
            return self.enum(*rest)[1]
        if kind == "struct":
            return self.struct(*rest)[0]
        if kind == "xstruct":
            return self.struct(*rest)[1]
        if kind == "layout":
            return self.layout(rest[0], rest[1:])
        if kind == "fn":
            return self.fn(*rest)[0]
        if kind == "xfn":
            return self.fn(*rest)[1]
        if kind == "modes":
            return self.modes()[0]
        if kind == "xmodes":
            return self.modes()[1]
        if kind == "defines":
            return self.defines(*rest)[0]
        if kind == "xdefines":
            return self.defines(*rest)[1]
        if kind == "shim":
            return self.shim(rest[0])
        if kind == "pin":
            return [
                "-- | @GHOSTTY_COMMIT@, the libghostty-vt commit this binding was generated",
                "-- against. The linked library's @VERSION_BUILD@ must be exactly this",
                "-- (DESIGN.md §3.4, §4.7).",
                "ghosttyPinnedCommit :: ByteString",
                f'ghosttyPinnedCommit = "{self.commit}"',
            ]
        if kind == "enumrows":
            rows = ",\n".join(self.rows)
            return ["  [ " + rows.removeprefix("    ") + "\n  ]"]
        sys.exit(f"gen-ghostty-ffi: unknown directive {kind}")

    def render(self, template: Path) -> str:
        banner = BANNER.format(src=template.as_posix())
        res = [f"/* {banner} */\n" if template.name.endswith(".h.in") else f"-- {banner}\n"]
        for line in template.read_text().splitlines():
            m = re.match(r"^(\s*)\{\{(.*)\}\}\s*$", line)
            if not m:
                res.append(line + "\n")
                continue
            ind, args = m.group(1), m.group(2).split()
            lines = self.expand(args)
            if args[0].startswith("x"):
                res += [f"{ind}{e},\n" for e in lines]
            else:
                res += [l + "\n" for l in "\n".join(lines).split("\n")]
        return "".join(res)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed file is stale")
    parser.add_argument("--include", type=Path, help="the libghostty-vt include directory")
    args = parser.parse_args()
    commit = (PKG / "GHOSTTY_COMMIT").read_text().strip()
    gen = Gen(Headers(args.include or Path("_deps/ghostty") / commit / "include"), commit)

    # Sources first, so that {{enumrows}} in the test sees every enum.
    templates = sorted(GEN.rglob("*.in"), key=lambda p: (p.parts[2] == "test", p.as_posix()))
    stale = []
    for t in templates:
        out = PKG / t.relative_to(GEN).with_suffix("")
        text = gen.render(t)
        if args.check:
            if not out.exists() or out.read_text() != text:
                stale.append(out)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text)
    for s in stale:
        print(f"stale   {s}")
    if args.check:
        if stale:
            print("gen-ghostty-ffi: run python3 scripts/gen-ghostty-ffi.py and commit the result")
            return 1
        print(f"gen-ghostty-ffi: {len(templates)} generated files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
